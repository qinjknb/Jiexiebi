/**
  ******************************************************************************
  * @file    robot_config.h
  * @brief   机械臂固件配置（DOFBOT Pro 6 轴 + 德晟总线舵机 v4.01）
  *
  * 换机械臂 / 换舵机 ID / 换速度，只改本文件，不用动逻辑代码。
  * 舵机侧寄存器与协议见《德晟串口智能舵机协议文件 v4.01.pdf》。
  ******************************************************************************
  */

#ifndef __ROBOT_CONFIG_H
#define __ROBOT_CONFIG_H

#include "stm32f10x.h"

/* ========================================================================
 * 1. 关节与舵机 ID
 *    关节 0..5 依次为：Arm1(底座旋转) / Arm2(大臂) / Arm3(小臂) /
 *                      Arm4(腕俯仰)  / Arm5(腕旋转) / grip(夹爪)
 * ---------------------------------------------------------------------- */
#define ARM_JOINT_NUM           6U

/* 6 个舵机在总线上的 ID（出厂按 1~6 排列；若你的不一样就改这里） */
#define ARM_SERVO_IDS           { 1U, 2U, 3U, 4U, 5U, 6U }

/* 舵机上电中位（机械零位对应的原始位置 0~4095，一般 2047 附近） */
#define ARM_HOME_TICKS          { 2047, 2047, 2047, 2047, 2047, 2047 }

/* 每个关节允许的最小/最大位置（软限位，防止撞机械结构）
 * 默认整车行程不限制，标定完请按实际情况收窄，例如 Arm2 大臂：
 *   ARM_TICK_MIN { 2047, 700, 900, 1200, 0, 1200 } */
#define ARM_TICK_MIN            { 0, 0, 0, 0, 0, 0 }
#define ARM_TICK_MAX            { 4095, 4095, 4095, 4095, 4095, 4095 }

/* 每个关节最大角速度（度/秒），固件内部按此做梯形限速，防甩臂 */
#define ARM_MAX_DPS             { 240U, 200U, 240U, 240U, 240U, 180U }

/* ========================================================================
 * 2. 串口与总线
 * ---------------------------------------------------------------------- */
/* STM32 <-> 总线舵机（USART1） */
#define ARM_SERVO_BAUD          115200U

/* 舵机总线接法（与 Servo.h 里的 SERVO_PIN_* 对应）：
 *   0 = 双线：PA9=TX(推挽) + PA10=RX(输入)   <-- 经"总线舵机驱动板 UART 口"时用这个
 *   1 = 单线半双工，只用 PA10
 *   2 = 单线半双工，只用 PA9                 <-- 不经驱动板、直接接舵机数据线时用这个
 * 运行时也可以发文本命令  WIRING 0|1|2  临时切换，不用重新烧录。 */
#define ARM_SERVO_WIRING        2U      /* 当前硬件：PA9 单线直连舵机数据线 */

/* STM32 <-> 电脑（USART2，PA2=TX / PA3=RX，接 USB-TTL）
 * 115200 打满 50Hz*6 关节命令绰绰有余；想更快可改 460800（CH340 也支持） */
#define ARM_LINK_BAUD           115200U

/* 舵机总线刷新周期（ms）：20 = 50Hz，10 = 100Hz。
 * 越短越顺滑，但总线占用越高。115200 下 20ms 是稳妥值。 */
#define ARM_SERVO_PERIOD_MS     20U

/* 一次下发 6 个舵机的方式：
 *   0 = SYNC WRITE(0x83) 广播同步写    —— 推荐，一帧搞定，无应答冲突
 *   1 = 逐个 WRITE(0x03)，每帧等应答   —— 兼容性最好，占用总线多
 *   2 = REG_WRITE(0x04)*6 + ACTION(0x05) —— 相当于方式 1 的异步版
 * 可用上位机命令 BUSMODE 在运行时切换，不用重新烧录。 */
#define ARM_BUS_MODE            0U

/* 舵机满行程角度（0~4095 对应多少度）。德晟 300° 舵机填 300 */
#define ARM_SERVO_RANGE_DEG     300U

/* 电脑多久没发新目标就自动停机保护（ms） */
#define ARM_LINK_TIMEOUT_MS     400U

/* 从 IDLE 进入跟随时的软启动时间（ms），防止第一个目标跳变 */
#define ARM_SOFTSTART_MS        400U

/* ========================================================================
 * 3. 位置回读（把舵机真实位置读回来，供 ROS 侧 /joint_states 使用）
 *    ARM_READBACK_DIV = 每多少个控制周期读一个舵机（6 个舵机轮询一圈）
 * ---------------------------------------------------------------------- */
#define ARM_READBACK_ENABLE     1U
#define ARM_READBACK_DIV        5U
#define ARM_READBACK_TIMEOUT_MS 5U

/* 状态帧默认上报频率（Hz，0=关闭）。
 * 默认关：老上位机(ServoHost)只认文本，收到二进制状态帧会刷屏。
 * ROS 的 dofbot_hw_bridge 连上后会用 SET_TELEM 自动打开（默认 25Hz）。
 * 想手动开：文本命令  TELEM 25 */
#define ARM_TELEM_RATE_HZ       0U

/* 帧缓冲/环形缓冲尺寸 */
#define LINK_RX_BUF_SIZE        192U
#define LINK_TX_BUF_SIZE        192U
#define LINK_MAX_PAYLOAD        32U
#define LINK_TEXT_LINE_MAX      64U

#endif /* __ROBOT_CONFIG_H */
